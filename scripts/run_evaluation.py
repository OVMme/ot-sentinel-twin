#!/usr/bin/env python3
"""Run the labelled-scenario evaluation and write JSON + a Markdown coverage matrix.

Usage (from the repository root, with the backend installed):
    python scripts/run_evaluation.py --seeds 1337 2024 4242

Outputs:
    datasets/synthetic/evaluation_results.json
    docs/EVALUATION_RESULTS.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.evaluation.harness import run_evaluation  # noqa: E402


def to_markdown(result: dict) -> str:
    s = result["summary"]
    lines = [
        "# Detection Evaluation Results",
        "",
        "> Generated by `scripts/run_evaluation.py` from executed simulation runs. All data is synthetic; the",
        "> numbers describe this detector on this simulated plant only.",
        "",
        f"- Generated: {result['generated_at']}",
        f"- Seeds: {', '.join(str(x) for x in result['seeds'])}",
        f"- Runs: {s['runs']} ({s['anomalous_runs']} anomalous, "
        f"{s['normal_operation_hours']:.2f} h of labelled normal operation)",
        f"- Wall time: {result['wall_time_s']} s",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| True positives (detected anomalous runs) | {s['true_positives']} |",
        f"| False negatives (missed anomalous runs) | {s['false_negatives']} |",
        f"| Attributed alerts | {s['attributed_alerts']} |",
        f"| False-positive alerts | {s['false_positive_alerts']} |",
        f"| Precision (alert level) | {s['precision']:.3f} |",
        f"| Recall (scenario level) | {s['recall']:.3f} |",
        f"| F1 | {s['f1']:.3f} |",
        f"| Mean detection latency | {s['latency_mean_s']} s |",
        f"| Max detection latency | {s['latency_max_s']} s |",
        f"| False positives during normal operation | {s['normal_operation_false_positives']} in "
        f"{s['normal_operation_hours']:.2f} h |",
        f"| Incident classification accuracy | {s['classification_accuracy']} |",
        "",
        "## Coverage matrix",
        "",
        "| Scenario | Expected detection | Actual detection (rules fired) | Latency mean / max | Classification "
        "(expected -> actual) | Runs detected | FP alerts | Result |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for m in s["coverage_matrix"]:
        exp = ", ".join(m["expected_rules"]) or "none (no alerts)"
        fired = ", ".join(m["rules_fired"]) or "none"
        lat = "-" if m["latency_mean_s"] is None else f"{m['latency_mean_s']} s / {m['latency_max_s']} s"
        cls = (
            "-"
            if not m["classification_expected"]
            else f"{m['classification_expected']} -> {', '.join(m['classifications']) or 'none'}"
        )
        det = f"{m['detected']}/{m['runs']}" if m["anomalous"] else "n/a"
        lines.append(
            f"| {m['scenario']} | {exp} | {fired} | {lat} | {cls} | {det} | {m['false_positives']} | {m['result']} |"
        )
    rob = result.get("robustness")
    if rob:
        lines += [
            "",
            "## Robustness: plant/model mismatch sweep",
            "",
            "The nominal results above use a detector whose process model matches the simulator exactly. This",
            "sweep makes the simulated plant deviate from the detector's model to show where detection degrades.",
            "",
            "> " + " ".join(rob["description"].split()),
            "",
            "| Severity | Precision | Recall | F1 | FP alerts (normal op.) | Classification acc. | Rules with FPs | "
            "Missed scenarios |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for r in rob["sweep"]:
            lines.append(
                f"| {r['severity']}x | {r['precision']:.3f} | {r['recall']:.3f} | {r['f1']:.3f} | "
                f"{r['false_positive_alerts']} ({r['normal_operation_false_positives']}) | "
                f"{r['classification_accuracy']} | {', '.join(r['false_positive_rules']) or '-'} | "
                f"{', '.join(r['missed']) or '-'} |"
            )
    lines += ["", "## Definitions", ""]
    for k, v in result["definitions"].items():
        lines.append(f"- **{k}**: {v}")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--seeds", type=int, nargs="+", default=[1337, 2024, 4242])
    args = ap.parse_args()
    result = run_evaluation(tuple(args.seeds))
    out_json = ROOT / "datasets" / "synthetic" / "evaluation_results.json"
    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_json.write_text(json.dumps(result, indent=1), encoding="utf-8")
    out_md = ROOT / "docs" / "EVALUATION_RESULTS.md"
    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_md.write_text(to_markdown(result), encoding="utf-8")
    s = result["summary"]
    print(
        f"precision={s['precision']} recall={s['recall']} f1={s['f1']} "
        f"latency_mean={s['latency_mean_s']}s FP={s['false_positive_alerts']} "
        f"normal_FP={s['normal_operation_false_positives']} in {s['normal_operation_hours']} h"
    )
    print(f"wrote {out_json.relative_to(ROOT)} and {out_md.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
