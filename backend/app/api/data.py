# ----------------------------------------------------------------------------- reports
@router.get("/reports/{incident_id}", tags=["reports"])
def report(
    incident_id: str = Path(pattern=INCIDENT_ID_PATTERN),
    fmt: Literal["json", "md"] = Query("json", alias="format"),
    download: bool = False,
    rt: SimulationRuntime = Depends(get_runtime),
    repo: Repository = Depends(get_repo),
) -> Response:
    rt.flush_sync()
    r = build_report(repo, incident_id)
    if r is None:
        raise ApiError(404, "not_found", f"Incident {incident_id} not found.")
    headers = _attachment(f"otst-report-{incident_id}.{fmt}") if download else {}
    if fmt == "md":
        return PlainTextResponse(render_markdown(r), media_type="text/markdown", headers=headers)
    return Response(json.dumps(r, indent=1), media_type="application/json", headers=headers)


