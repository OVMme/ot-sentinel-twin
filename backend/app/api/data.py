@router.put("/detections/rules/{rule_id}", tags=["detection"], dependencies=[Depends(require_write)])
async def update_rule(
    body: RuleUpdateRequest,
    rule_id: str = Path(pattern=RULE_ID_PATTERN),
    rt: SimulationRuntime = Depends(get_runtime),
    repo: Repository = Depends(get_repo),
    who: str = Depends(analyst),
) -> dict[str, Any]:
    changes = body.model_dump(exclude_none=True)
    try:
        cfg = rt.update_rule(rule_id, changes)
    except KeyError as exc:
        raise ApiError(404, "not_found", f"Unknown rule '{rule_id}'.") from exc
    except ValueError as exc:
        raise ApiError(422, "invalid_config", str(exc)) from exc
    repo.audit(who, "rule.update", f"rule:{rule_id}", changes)
    return {"rule_id": rule_id, "config": cfg}


