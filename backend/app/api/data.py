def _attachment(name: str) -> dict[str, str]:
    safe = "".join(c for c in name if c.isalnum() or c in "-_.")[:120] or "export"
    return {"Content-Disposition": f'attachment; filename="{safe}"'}


# ----------------------------------------------------------------------------- system
@router.get("/health", response_model=HealthResponse, tags=["system"])
def health(
    rt: SimulationRuntime = Depends(get_runtime), repo: Repository = Depends(get_repo)
) -> HealthResponse:
    db: Literal["ok", "error"] = "ok"
    try:
        with repo.session() as s:
            s.execute(text("SELECT 1"))
    except Exception:  # pragma: no cover
        db = "error"
    status: Literal["ok", "degraded"] = "ok" if db == "ok" and rt.status != "error" else "degraded"
    return HealthResponse(
        status=status, version=rt.settings.version, simulation=rt.status, run_id=rt.run_id, database=db
    )


