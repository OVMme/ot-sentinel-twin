@router.get("/telemetry/history", tags=["telemetry"])
def telemetry_history(
    run_id: str | None = Query(None, pattern=RUN_ID_PATTERN),
    from_seq: int = Query(0, ge=0),
    limit: int = Query(500, ge=1, le=5000),
    full: bool = Query(
        False, description="Return full payloads (signals, quality, truth) instead of columns"
    ),
    rt: SimulationRuntime = Depends(get_runtime),
    repo: Repository = Depends(get_repo),
) -> dict[str, Any]:
    rid = run_id or rt.run_id
    if rid == rt.run_id:
        rt.flush_sync()
    items = repo.telemetry_page(rid, from_seq, limit, full)
    next_seq = items[-1]["seq"] + 1 if len(items) == limit else None
    return {"run_id": rid, "from_seq": from_seq, "limit": limit, "next_from_seq": next_seq, "items": items}


@router.get("/telemetry/export", tags=["telemetry"])
def telemetry_export(
    run_id: str | None = Query(None, pattern=RUN_ID_PATTERN),
    fmt: Literal["csv", "json"] = Query("csv", alias="format"),
    rt: SimulationRuntime = Depends(get_runtime),
    repo: Repository = Depends(get_repo),
) -> Response:
    rid = run_id or rt.run_id
    if rid == rt.run_id:
        rt.flush_sync()
    rows: list[dict[str, Any]] = []
    seq = 0
    while len(rows) < 200_000:
        page = repo.telemetry_page(rid, seq, 5000, False)
        if not page:
            break
        rows.extend(page)
        seq = page[-1]["seq"] + 1
    if fmt == "json":
        body = json.dumps(
            {"notice": "Synthetic data generated by OT Sentinel Twin", "run_id": rid, "rows": rows}
        )
        return Response(
            body, media_type="application/json", headers=_attachment(f"otst-telemetry-{rid}.json")
        )
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=["seq", "t", "ts", *SAMPLE_COLUMNS])
    writer.writeheader()
    writer.writerows(rows)
    return Response(buf.getvalue(), media_type="text/csv", headers=_attachment(f"otst-telemetry-{rid}.csv"))


