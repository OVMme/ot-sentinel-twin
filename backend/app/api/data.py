@router.get("/replay/{run_id}", tags=["replay"])
def replay_run(
    run_id: str = Path(pattern=RUN_ID_PATTERN),
    from_seq: int = Query(0, ge=0),
    limit: int = Query(20000, ge=1, le=20000),
    rt: SimulationRuntime = Depends(get_runtime),
    repo: Repository = Depends(get_repo),
) -> dict[str, Any]:
    """Recorded samples (columnar) plus detection, incident and scenario markers. Never re-simulates."""
    if run_id == rt.run_id:
        rt.flush_sync()
    run = repo.get_run(run_id)
    if run is None:
        raise ApiError(404, "not_found", f"Run {run_id} not found.")
    cols = repo.replay_columns(run_id, from_seq, limit)
    _, dets = repo.list_detections(run_id, None, None, None, 500, 0)
    _, incs = repo.list_incidents(run_id, None, None, 200, 0)
    n = len(cols["seq"])
    return {
        "run": run,
        "from_seq": from_seq,
        "count": n,
        "next_from_seq": cols["seq"][-1] + 1 if n == limit else None,
        "columns": cols,
        "detections": sorted(dets, key=lambda d: d["raised_t"]),
        "incidents": incs,
        "scenario_events": repo.scenario_events(run_id),
    }


